export function makeT(lang) {
  const table = STRINGS[lang] || STRINGS.hi;
  return (key, vars) => {
    let out = table[key] ?? STRINGS.en[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) out = out.replaceAll(`{${k}}`, v);
    return out;
  };
}
